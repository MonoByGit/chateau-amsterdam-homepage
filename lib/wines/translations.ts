const COUNTRY_MAP_NL: Record<string, string> = {
  France: "Frankrijk",
  Germany: "Duitsland",
  Italy: "Italië",
  Spain: "Spanje",
  Netherlands: "Nederland",
  "Various EU countries": "Verschillende EU-landen",
  "Italy, France": "Italië & Frankrijk",
  "France & Italy": "Frankrijk & Italië",
  "Italy and France": "Italië en Frankrijk",
  "Spain and France": "Spanje en Frankrijk",
  "Germany and Italy": "Duitsland en Italië",
};

const REGION_MAP_NL: Record<string, string> = {
  Various: "Verschillende",
  Tuscany: "Toscane",
  "Tuscany (IT), Saint-Émilion (FR)": "Toscane (IT), Saint-Émilion (FR)",
  "Languedoc-Roussillon & Tuscany": "Languedoc-Roussillon & Toscane",
};

export function translateRegion(region: string | null, lang: "nl" | "en"): string | null {
  if (!region) return null;
  if (lang === "en") return region;

  let result = region;
  for (const [en, nl] of Object.entries(COUNTRY_MAP_NL)) {
    result = result.replace(new RegExp(`\\b${en}\\b`, "g"), nl);
  }
  for (const [en, nl] of Object.entries(REGION_MAP_NL)) {
    result = result.replace(new RegExp(`\\b${en}\\b`, "g"), nl);
  }
  return result;
}

export function extractAbv(
  experimentalMeta: string | null | undefined,
  text: string | null | undefined,
  lang: "nl" | "en"
): string | null {
  if (experimentalMeta) {
    const clean = experimentalMeta.trim().replace("%", "").trim();
    if (clean) {
      return lang === "nl" ? `${clean.replace(".", ",")}%` : `${clean.replace(",", ".")}%`;
    }
  }

  if (!text) return null;

  const match = text.match(/(?:at|bottled at|alcoholpercentage:?)\s*(\d+(?:[.,]\d+)?)\s*(?:%|percent)/i);
  if (match && match[1]) {
    const val = match[1];
    return lang === "nl" ? `${val.replace(".", ",")}%` : `${val.replace(",", ".")}%`;
  }

  const generalMatch = text.match(/(\d+(?:[.,]\d+)?)\s*%\s*(?:vol|alcohol)?/i);
  if (generalMatch && generalMatch[1]) {
    const val = generalMatch[1];
    return lang === "nl" ? `${val.replace(".", ",")}%` : `${val.replace(",", ".")}%`;
  }

  return null;
}
